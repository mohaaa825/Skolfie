"""
skolfie/data/sources/m4gt.py
----------------------------
Loader for M4GT-Bench English, task 1 monolingual (binary human vs machine,
multi-generator), from mbzuai-nlp/M4GT-Bench.

On-disk format (from the repo's src/transformer_detector.py and
gltr_detector.ipynb): JSONL, one text per line, read there with
`pd.read_json(path, lines=True)`:

    {"text": "...", "label": 0, "model": "human", "source": "wikihow", ...}

`label` is 0 = human, 1 = machine (subtask B files use a multi-class label,
so `model` is the field relied on here). Other columns may be present
("parallel", per-seed split columns such as "chatGPT_0", "id") and are
ignored. The SemEval-2024 Task 8 files built from the same data
(subtaskA_train_monolingual.jsonl etc.) have the same fields plus "id" and
are read the same way.

`model` values seen in the released English file: human, chatGPT, davinci,
cohere, dolly, bloomz, gpt4, and in the OUTFOX part gpt-3.5-turbo,
davinci-003, dolly-v2-12b. They are normalised with GENERATOR_MAP. The
canonical names come from the source itself: the original M4 data files
(github.com/mbzuai-nlp/M4, data/*.jsonl) record ChatGPT generations as
"gpt-3.5-turbo", davinci as "text-davinci-003" and Dolly as "dolly-v2-12b".

English only: rows are kept when `source` is one of the English domains
(wikipedia, wikihow, reddit, arxiv, peerread, outfox, the list used by the
repo's own code) and, if a language field exists, it says English. Rows
from other sources (multilingual files use language names as `source`) are
skipped and counted in a log warning.

There is no programmatic download: the data is in a Google Drive folder.
"""

from __future__ import annotations

import logging
from collections import Counter
from collections.abc import Iterator
from pathlib import Path

from skolfie.data.schema import Record
from skolfie.data.sources._common import (
    iter_jsonl,
    missing_files_error,
    pick,
    split_from_name,
)

log = logging.getLogger(__name__)

NAME = "m4gt"
DESCRIPTION = (
    "M4GT-Bench English (task 1, monolingual): human and machine text from Wikipedia, "
    "WikiHow, Reddit ELI5, arXiv abstracts, PeerRead reviews and OUTFOX essays, generated by "
    "davinci-003, ChatGPT, GPT-4, Cohere, Dolly-v2 and BLOOMz."
)
CITATION = (
    "Wang, Y., Mansurov, J., Ivanov, P., Su, J., Shelmanov, A., Tsvigun, A., Afzal, O. M., "
    "Mahmoud, T., Puccetti, G., Arnold, T., et al. (2024). M4GT-Bench: Evaluation Benchmark "
    "for Black-Box Machine-Generated Text Detection. ACL 2024. arXiv:2402.11175."
)
LICENSE_NOTE = (
    "No licence file in the M4GT-Bench repo; the human texts inherit their sources' licences "
    "(Wikipedia CC-BY-SA, WikiHow CC-BY-NC-SA, Reddit, arXiv, PeerRead). Research use only."
)

DRIVE_URL = "https://drive.google.com/drive/folders/1xC-n5hHiXmaCLmA0q3p8Cbyd7Dk0dpDE"

MANUAL_DOWNLOAD = f"""\
M4GT-Bench manual download: open the dataset folder linked from
https://github.com/mbzuai-nlp/M4GT-Bench ("Dataset"): {DRIVE_URL}
and download the English task-1 (subtask A, monolingual) file, SubtaskA.jsonl
(SubtaskA_split.jsonl is the same data plus split columns; one of the two is enough),
into <raw_dir>/{NAME}/. Every *.jsonl file in that directory is read, so do not put both
copies there. The SemEval-2024 Task 8 subtask A monolingual files
(subtaskA_train_monolingual.jsonl, subtaskA_dev_monolingual.jsonl, ...) are also accepted.
`gdown --folder {DRIVE_URL}` can fetch the whole folder from a shell.
"""

# M4GT `source` -> coarse schema domain. Subdomain keeps the original value.
DOMAIN_MAP = {
    "wikipedia": "other",  # encyclopedia articles on any topic
    "wikihow": "technical",  # how-to instructions
    "reddit": "qa",  # Reddit ELI5 answers
    "reddit_eli5": "qa",
    "eli5": "qa",
    "arxiv": "academic",  # paper abstracts
    "peerread": "academic",  # peer reviews of NLP papers
    "outfox": "academic",  # student essays (OUTFOX)
}

GENERATOR_MAP = {
    "chatgpt": "gpt-3.5-turbo",
    "gpt-3.5-turbo": "gpt-3.5-turbo",
    "davinci": "text-davinci-003",
    "davinci-003": "text-davinci-003",
    "text-davinci-003": "text-davinci-003",
    "dolly": "dolly-v2-12b",
    "dolly-v2": "dolly-v2-12b",
    "dolly2": "dolly-v2-12b",
    "dolly-v2-12b": "dolly-v2-12b",
    "bloomz": "bloomz",
    "bigscience/bloomz": "bloomz",
    "cohere": "cohere",
    "command-xlarge-nightly": "cohere",
    "cohere-xlarge-nightly": "cohere",
    "gpt4": "gpt-4",
    "gpt-4": "gpt-4",
    "flant5": "flan-t5",
    "flan-t5": "flan-t5",
    "llama": "llama",
}

TEXT_KEYS = ("text",)
MODEL_KEYS = ("model", "generator")
SOURCE_KEYS = ("source", "domain")
LABEL_KEYS = ("label",)
ID_KEYS = ("id",)
LANG_KEYS = ("language", "lang")
SPLIT_KEYS = ("split",)
ENGLISH = {"en", "eng", "english"}


def normalise_generator(model: str) -> str:
    key = model.strip().lower()
    return GENERATOR_MAP.get(key, key)


def _files(directory: Path) -> list[Path]:
    if not directory.is_dir():
        return []
    return sorted(p for p in directory.rglob("*.jsonl") if not p.name.startswith("."))


def _label_and_generator(row: dict, where: str) -> tuple[str, str]:
    model = pick(row, MODEL_KEYS, where, "model", default=None)
    if model is not None and str(model).strip():
        model = str(model)
        if model.strip().lower() == "human":
            return "human", "human"
        return "ai", normalise_generator(model)
    label = pick(row, LABEL_KEYS, where, "model or label")
    if str(label).strip().lower() in {"0", "human"}:
        return "human", "human"
    if str(label).strip().lower() in {"1", "machine", "ai", "generated"}:
        return "ai", "unknown"
    raise ValueError(f"{where}: cannot interpret label {label!r} without a model field")


def load(raw_dir: Path, download: bool = True) -> Iterator[Record]:
    """Yield English M4GT-Bench task-1 Records from `raw_dir/m4gt/*.jsonl`.

    `download` is accepted for interface compatibility; the data lives on Google
    Drive, so missing files always raise FileNotFoundError with instructions.
    """
    directory = Path(raw_dir) / NAME
    files = _files(directory)
    if not files:
        if download:
            log.warning("m4gt: no automatic download (Google Drive); see MANUAL_DOWNLOAD")
        raise missing_files_error(NAME, directory, "SubtaskA.jsonl", MANUAL_DOWNLOAD)

    for path in files:
        rel = path.relative_to(directory).with_suffix("").as_posix()
        file_split = split_from_name(path.name)
        skipped: Counter[str] = Counter()
        for index, row in iter_jsonl(path):
            where = f"{path}:{index + 1}"
            text = pick(row, TEXT_KEYS, where, "text")
            source = str(pick(row, SOURCE_KEYS, where, "source/domain")).strip()
            lang = pick(row, LANG_KEYS, where, "language", default=None)
            if lang is not None and str(lang).strip().lower() not in ENGLISH:
                skipped[f"language={lang}"] += 1
                continue
            domain = DOMAIN_MAP.get(source.lower())
            if domain is None:
                skipped[source] += 1
                continue
            if not isinstance(text, str) or not text.strip():
                continue
            label, generator = _label_and_generator(row, where)
            local_id = pick(row, ID_KEYS, where, "id", default=None)
            if local_id is None or str(local_id).strip() == "":
                local_id = index  # a null id would make every such row collide
            split = pick(row, SPLIT_KEYS, where, "split", default=file_split) or ""
            yield Record(
                id=f"{NAME}:{rel}:{local_id}", text=text.strip(), label=label,
                generator=generator, domain=domain, subdomain=source.lower(), source=NAME,
                split_hint=str(split),
            )
        if skipped:
            log.warning(
                "m4gt: %s: skipped %d non-English or unknown-source rows: %s",
                path, sum(skipped.values()), dict(skipped.most_common(10)),
            )
