"""
skolfie/deploy/hf_space.py
---------------------------
A permanent Skolfie website on Hugging Face Spaces ("CPU basic" hardware is
enough; Hugging Face hosts Gradio Spaces only for PRO accounts).

    build_space(bundle_dir, out_dir, git_ref=..., versions=collect_versions())
        writes a ready-to-upload Space folder (no network):
            README.md        Space settings (YAML front matter) and a short intro
            requirements.txt Skolfie from GitHub at `git_ref`, plus exact pins of
                             the libraries the pickled models need (torch from
                             the CPU wheel index)
            app.py           starts skolfie.app.gradio_app on 0.0.0.0:7860 with
                             ./bundle; the login comes from the Space secret
                             SKOLFIE_APP_AUTH ("user:password")
            packages.txt     system packages (libgomp1 for LightGBM)
            .gitattributes   model files go to Git LFS
            bundle/          the bundle (`skolfie bundle`), hard-linked or copied
    publish_space(space_dir, "user/name", token, private=..., auth="user:pw")
        creates the Space if needed, sets the SKOLFIE_APP_AUTH secret and
        uploads the folder (needs huggingface_hub); returns the Space page URL.

The token is only passed to huggingface_hub: never printed, logged or
written to disk. The models are loaded with joblib, so the pins in
requirements.txt must match the environment that trained them: build with
`collect_versions()` run where the models were trained (the Colab runtime).
"""

from __future__ import annotations

import json
import os
import re
import shutil
import sys
from pathlib import Path
from typing import Mapping, Optional

DEFAULT_REPO_URL = "https://github.com/mohaaa825/Skolfie"
TORCH_CPU_INDEX = "https://download.pytorch.org/whl/cpu"
AUTH_SECRET = "SKOLFIE_APP_AUTH"
PORT = 7860
# Libraries pinned exactly in requirements.txt (pip distribution names), when installed.
PINNED = ("numpy", "pandas", "scikit-learn", "scipy", "lightgbm", "joblib", "torch",
          "transformers", "tokenizers", "gradio")
LFS_PATTERNS = ("*.joblib", "*.pt", "*.bin", "*.safetensors")
# Debian packages the Space installs (LightGBM's wheel needs the OpenMP runtime).
SYSTEM_PACKAGES = ("libgomp1",)
# First line of the generated app.py: marks a folder this module may overwrite.
GENERATED_MARKER = "# Generated by `skolfie space build`: rebuild it instead of editing."
SHORT_DESCRIPTION = "Probabilistic AI-text checker for teachers"
_REPO_ID_RE = re.compile(r"^[A-Za-z0-9][A-Za-z0-9._-]*/[A-Za-z0-9][A-Za-z0-9._-]*$")


# --------------------------------------------------------------------------- #
# Versions
# --------------------------------------------------------------------------- #
def collect_versions() -> dict[str, str]:
    """{distribution: version} of the installed PINNED libraries, plus "python": "3.x.y"."""
    from importlib import metadata

    versions: dict[str, str] = {}
    for name in PINNED:
        try:
            versions[name] = metadata.version(name)
        except metadata.PackageNotFoundError:
            continue
    versions["python"] = ".".join(str(v) for v in sys.version_info[:3])
    return versions


def _public_version(version: str) -> str:
    """'2.5.1+cu121' -> '2.5.1': local suffixes name a build, not a version pip can find."""
    return str(version).strip().split("+", 1)[0]


def _python_minor(version: str) -> str:
    parts = _public_version(version).split(".")
    if len(parts) < 2 or not all(p.isdigit() for p in parts[:2]):
        raise ValueError(f"python version must look like 3.12 or 3.12.4, got {version!r}")
    return f"{parts[0]}.{parts[1]}"


# --------------------------------------------------------------------------- #
# URLs
# --------------------------------------------------------------------------- #
def check_repo_id(repo_id: str) -> str:
    if not isinstance(repo_id, str) or not _REPO_ID_RE.match(repo_id.strip()):
        raise ValueError(f"the Space must be named like yourname/skolfie, got {repo_id!r}")
    return repo_id.strip()


def space_page_url(repo_id: str) -> str:
    """The Space's page on huggingface.co (settings, build and run logs)."""
    return f"https://huggingface.co/spaces/{check_repo_id(repo_id)}"


def space_site_url(repo_id: str) -> str:
    """The website itself: https://{user}-{name}.hf.space (lowercase, '.' and '_' -> '-')."""
    user, name = check_repo_id(repo_id).split("/")
    sub = re.sub(r"[._]", "-", f"{user}-{name}".lower())
    return f"https://{sub}.hf.space"


# --------------------------------------------------------------------------- #
# Space files
# --------------------------------------------------------------------------- #
def _yaml_str(value: str) -> str:
    return json.dumps(str(value), ensure_ascii=False)  # a JSON string is a YAML scalar


def readme_text(*, title: str, repo_url: str, git_ref: str, versions: Mapping[str, str],
                public: bool) -> str:
    meta = [
        ("title", _yaml_str(title)),
        ("emoji", "📝"),
        ("colorFrom", "blue"),
        ("colorTo", "indigo"),
        ("sdk", "gradio"),
        ("sdk_version", _yaml_str(_public_version(versions["gradio"]))),
        ("app_file", "app.py"),
    ]
    if versions.get("python"):
        meta.append(("python_version", _yaml_str(_python_minor(versions["python"]))))
    meta += [("pinned", "false"), ("short_description", _yaml_str(SHORT_DESCRIPTION))]
    access = ("Anyone with the link can use it (no login)." if public else
              f"It asks for a login, set as the Space secret `{AUTH_SECRET}` "
              "(`user:password`) under Settings → Variables and secrets.")
    body = f"""
# {title}

Skolfie checks English texts, such as student essays, for AI-generated writing. Paste an
essay or upload a .txt, .docx or .pdf to get a verdict (Human / AI / Mixed / Uncertain), an
AI likelihood, the parts that look AI-written and the reasons.

**The result is a probabilistic aid, never sole proof.** Do not use it as the only basis for
a misconduct decision; known limitations (e.g. for non-native writers) are shown with each
result.

{access} Feedback sent from the app is stored on the Space's disk, which is reset when the
Space restarts.

Code: [{repo_url}]({repo_url}) at `{git_ref}`. This folder was generated by
`skolfie space build`; rebuild and publish it again rather than editing it here.
"""
    return "---\n" + "".join(f"{k}: {v}\n" for k, v in meta) + "---\n" + body


def requirements_text(*, repo_url: str, git_ref: str, versions: Mapping[str, str]) -> str:
    lines = [
        f"--extra-index-url {TORCH_CPU_INDEX}",
        f"skolfie[features,app] @ git+{repo_url.rstrip('/')}@{git_ref}",
    ]
    lines += [f"{name}=={_public_version(versions[name])}" for name in PINNED
              if versions.get(name)]
    return "\n".join(lines) + "\n"


def app_text(*, public: bool) -> str:
    from skolfie.app.gradio_app import NO_AUTH_FLAG

    extra = f", {NO_AUTH_FLAG!r}" if public else ""
    return f'''{GENERATED_MARKER}
"""
Skolfie on Hugging Face Spaces: starts the web app (skolfie.app.gradio_app) with the
models in ./bundle on port {PORT}. The login comes from the Space secret {AUTH_SECRET}
("user:password"), set under Settings -> Variables and secrets.
"""

import os
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
PUBLIC = {public!r}  # chosen at build time (skolfie space build --public)

os.environ.setdefault("TOKENIZERS_PARALLELISM", "false")
os.environ.setdefault("SKOLFIE_FEEDBACK", str(HERE / "feedback_data.csv"))


def main() -> None:
    if PUBLIC:
        if os.environ.pop("{AUTH_SECRET}", None):
            print("[skolfie] built with --public: ignoring the {AUTH_SECRET} secret.")
    elif not os.environ.get("{AUTH_SECRET}"):
        sys.exit(
            "[skolfie] No login is set, so the app will not start. In this Space go to "
            "Settings -> Variables and secrets -> New secret, name it {AUTH_SECRET} and give "
            "it the value user:password (a long password), then restart the Space. To serve "
            "without a login, rebuild with `skolfie space build --public`.")

    from skolfie.app.gradio_app import main as app_main

    app_main(["--bundle", str(HERE / "bundle"), "--host", "0.0.0.0", "--port", "{PORT}"{extra}])


if __name__ == "__main__":
    main()
'''


def gitattributes_text() -> str:
    return "".join(f"{p} filter=lfs diff=lfs merge=lfs -text\n" for p in LFS_PATTERNS)


def _link_or_copy(src: str, dst: str) -> str:
    try:
        os.link(src, dst)
    except OSError:  # another file system (e.g. Google Drive), or links not allowed
        shutil.copy2(src, dst)
    return dst


def _within(path: Path, parent: Path) -> bool:
    return path == parent or parent in path.parents


def _prepare_out_dir(out: Path) -> None:
    """Make `out` an empty folder; only a folder made by build_space may be cleared."""
    if out.exists() and not out.is_dir():
        raise ValueError(f"{out} exists and is not a folder")
    if out.is_dir() and any(out.iterdir()):
        app = out / "app.py"
        try:
            ours = app.read_text(encoding="utf-8").startswith(GENERATED_MARKER)
        except OSError:
            ours = False
        if not ours:
            raise ValueError(f"{out} is not empty and was not made by `skolfie space build`; "
                             "choose a new or empty folder")
        for child in out.iterdir():
            if child.is_dir() and not child.is_symlink():
                shutil.rmtree(child)
            else:
                child.unlink()
    out.mkdir(parents=True, exist_ok=True)


def build_space(bundle_dir: str | os.PathLike[str], out_dir: str | os.PathLike[str], *,
                repo_url: str = DEFAULT_REPO_URL, git_ref: str, versions: Mapping[str, str],
                title: str = "Skolfie", public: bool = False) -> Path:
    """
    Write a Hugging Face Space folder for the bundle `bundle_dir` (made by `skolfie bundle`)
    into `out_dir` and return it. `git_ref` is the Skolfie commit (or tag) the Space installs
    from `repo_url`; `versions` ({distribution: version, "python": "3.x.y"}, see
    `collect_versions`) gives the exact pins. `public=True` serves without a login.
    A non-empty `out_dir` is cleared first only if an earlier build_space made it.
    """
    from skolfie.service import BUNDLE_FILE

    bundle = Path(bundle_dir).resolve()
    out = Path(out_dir).resolve()
    if not (bundle / BUNDLE_FILE).is_file():
        raise ValueError(f"{bundle} is not a Skolfie bundle (no {BUNDLE_FILE}); make one with "
                         "`skolfie bundle`")
    if _within(bundle, out) or _within(out, bundle):
        raise ValueError("the bundle and the Space folder must not contain each other")
    if not str(git_ref or "").strip() or any(c.isspace() for c in str(git_ref).strip()):
        raise ValueError(f"git_ref must be a commit, tag or branch name, got {git_ref!r}")
    if not versions.get("gradio"):
        raise ValueError("versions must include gradio (the Space's sdk_version)")
    git_ref = str(git_ref).strip()

    _prepare_out_dir(out)
    files = {
        "README.md": readme_text(title=title, repo_url=repo_url, git_ref=git_ref,
                                 versions=versions, public=public),
        "requirements.txt": requirements_text(repo_url=repo_url, git_ref=git_ref,
                                              versions=versions),
        "app.py": app_text(public=public),
        "packages.txt": "".join(f"{p}\n" for p in SYSTEM_PACKAGES),
        ".gitattributes": gitattributes_text(),
    }
    for name, text in files.items():
        (out / name).write_text(text, encoding="utf-8")
    shutil.copytree(bundle, out / "bundle", copy_function=_link_or_copy,
                    ignore=shutil.ignore_patterns("*.tmp"))
    return out


# --------------------------------------------------------------------------- #
# Publishing
# --------------------------------------------------------------------------- #
def publish_space(space_dir: str | os.PathLike[str], repo_id: str, token: str, *,
                  private: bool, auth: Optional[str]) -> str:
    """
    Create the Space `repo_id` ("user/name") if it does not exist, set the secret
    SKOLFIE_APP_AUTH to `auth` ("user:password") when given, upload `space_dir` (a folder
    from build_space) and return the Space page URL. Bundle files no longer in the folder
    are deleted from the Space. `private` only applies when the Space is created.
    """
    from skolfie.app.gradio_app import parse_auth

    repo_id = check_repo_id(repo_id)
    folder = Path(space_dir)
    if not (folder / "app.py").is_file() or not (folder / "README.md").is_file():
        raise ValueError(f"{folder} is not a Space folder: make it with `skolfie space build`")
    if not token:
        raise ValueError("a Hugging Face token with the Write role is needed")
    if auth is not None:
        parse_auth(auth)  # ValueError unless user:password

    try:
        from huggingface_hub import HfApi
    except ImportError as exc:  # pragma: no cover - depends on the environment
        raise ImportError("publishing needs huggingface_hub: pip install huggingface_hub") \
            from exc

    api = HfApi(token=token)
    try:
        api.create_repo(repo_id, repo_type="space", space_sdk="gradio", exist_ok=True,
                        private=private)
    except Exception as exc:
        if getattr(getattr(exc, "response", None), "status_code", None) == 402:
            raise ValueError("Hugging Face refused to create the Space (402 Payment Required): "
                             "Gradio Spaces need a PRO subscription "
                             "(https://huggingface.co/pro). Subscribe, then publish again.") \
                from exc
        raise
    if auth:
        api.add_space_secret(repo_id, AUTH_SECRET, auth,
                             description="Skolfie login, user:password")
    api.upload_folder(repo_id=repo_id, repo_type="space", folder_path=str(folder),
                      commit_message="Update Skolfie (skolfie space publish)",
                      delete_patterns=["bundle/*"])
    return space_page_url(repo_id)
